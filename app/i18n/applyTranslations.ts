export type ApplyLang = "zh-TW" | "en";

const WEEKDAYS = {
  "zh-TW": ["日", "一", "二", "三", "四", "五", "六"],
  en: ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"],
};

/** "10月24日（六）" / "Sat 24 Oct", from a YYYY-MM-DD date. */
export function formatSessionDate(date: string, lang: ApplyLang): string {
  const d = new Date(`${date}T00:00:00Z`);
  const wd = WEEKDAYS[lang][d.getUTCDay()];
  if (lang === "zh-TW") return `${d.getUTCMonth() + 1}月${d.getUTCDate()}日（${wd}）`;
  const month = d.toLocaleString("en-GB", { month: "short", timeZone: "UTC" });
  return `${wd} ${d.getUTCDate()} ${month}`;
}

